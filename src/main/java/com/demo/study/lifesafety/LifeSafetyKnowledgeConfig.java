package com.demo.study.lifesafety;

import com.demo.chroma.doc.DocKnowledgeConfig;
import org.springframework.stereotype.Component;

import java.util.List;

/**
 * 生命安全与健康教育公共知识库配置（教育模块 · 面向中小学生）。
 *
 * <p>命名与教育部《生命安全与健康教育进中小学课程教材指南》（教材函〔2021〕3 号）对齐——
 * 那份指南就是本库的框架依据，语料也包含它。原名为"生死教育"，范围偏窄且说法偏学术；
 * 换成官方口径后，答辩时"我们按教育部指南的体系建的库"这句话是能站住的。
 *
 * <p>两个子库：生命与死亡认知（life）、哀伤陪伴（support）。
 * 语料放 {@code data/lifesafety-knowledge/}，按子目录或文件名前缀（life_/support_）归入子库。
 *
 * <h3>三个与其他知识库不同的地方</h3>
 * <ol>
 *   <li><b>显式开启三级过滤</b>（最后三个参数）：本领域的过度召回危害格外大——
 *       把"临终关怀护理流程"之类的片段拼进"我奶奶去世了我很难过"的上下文，
 *       会得到一段冷冰冰的流程说明；</li>
 *   <li><b>提示词里写死边界</b>：不做心理诊断、不渲染死亡细节、不把死亡浪漫化、
 *       出现自伤信号先安抚并引导求助（与 {@code CrisisGuard} 的硬拦截形成双保险）；</li>
 *   <li><b>免责声明必须带热线</b>：知识库答不了"我现在很难受"这种事，得把人导向能接住他的地方。</li>
 * </ol>
 *
 * <h3>为什么是"AI 组织表达"而不是"照抄资料"</h3>
 * 最初的提示词是"只能用上下文里的内容作答，没有就直接回【暂无匹配内容】"。
 * 那条规则对法律问答成立（法条本身就是要原样引用的），但对本领域<b>恰恰造出了最糟的体验</b>：
 * 语料是学术文献，学生问的是"人为什么会死"，检索一旦没命中，模型就回一句"无法解答"——
 * 看起来像知识库坏了，实际是把生成能力锁死了。
 * 现在的规则是：<b>以资料为依据，由 AI 读懂后重新组织成面向学生的解释</b>，
 * 并强制标注【资料】/【补充】区分出处，同时禁止编造数字、机构与政策名称。
 * 这样既保住了"有据可依"，又不至于空洞。
 *
 * <h3>阈值为什么比法律库宽（1.05 / 1.15，而非 0.85 / 1.08）</h3>
 * 法律库那组数是按<b>法条</b>语料定的——问句与条文用词高度重合，0.85 卡得住。
 * 本库语料是<b>学术文献与教材</b>，学生又用口语提问，语义距离天然更大；
 * 沿用 0.85 会把大量真正相关的段落切在第一道过滤上，表现就是"问什么都是暂无匹配内容"。
 * 放宽后仍保留相对 cutoff 负责切掉尾部噪声。
 */
@Component
public class LifeSafetyKnowledgeConfig extends DocKnowledgeConfig {

    public LifeSafetyKnowledgeConfig() {
        super(
            "lifesafety", "lifesafety_", "data/lifesafety-knowledge",
            List.of(
                new SubLibrary("life", "生命与死亡认知", List.of("生命", "死亡")),
                new SubLibrary("support", "哀伤陪伴", List.of("哀伤", "陪伴", "丧失"))
            ),
            "你是面向中小学生的生命安全与健康教育知识助手。回答要求：\n"
                + "1. 优先使用【参考资料】的内容：读懂之后组织成一段面向学生的连贯解释，"
                + "不要只把资料原句抄一遍，也不要罗列标题；\n"
                + "2. 资料不足或没有直接对应时，不要只回一句『暂无匹配内容』：\n"
                + "   先用一句话如实说明知识库里没有直接材料，再用通俗语言给出你力所能及的解释与建议；\n"
                + "3. 得分清来源：来自资料要点标注【资料】，你自己补充的标注【补充】；"
                + "涉及具体数字、机构名、法条、政策名称时不得编造；\n"
                + "4. 语气温和、平实、不评判、不说教；不渲染死亡细节，不把死亡浪漫化或美化；\n"
                + "5. 只做知识科普，不做心理诊断或治疗；对方讲到自己的痛苦时，鼓励他和可信任的成年人、"
                + "学校心理老师聊一聊，而不是替他下结论；\n"
                + "6. 若出现自伤、自杀等危险信号，停止科普，先表达关心与陪伴，"
                + "并请其立即联系可信任的成年人，或拨打全国心理援助热线 12356、共青团 12355；\n"
                + "7. 篇幅 200~400 字：先给结论，再分点解释，最后给一句可操作的建议。",
            5, 1.05, 5,
            "⚠️免责声明：本内容仅基于知识库资料提供生命安全与健康教育参考，不构成心理诊断或治疗建议。"
                + "如果你正经历难以承受的痛苦，请联系学校心理老师，或拨打全国心理援助热线 12356（24 小时）。",
            800, 80, 10,
            1.15, 10, true
        );
    }
}
