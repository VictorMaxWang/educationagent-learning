package com.demo.agent.toolguard;

/**
 * 工具守卫的三态裁决。
 *
 * <p>为什么必须是三态而不是布尔：规则匹配是关键词级的，天然会有"命中规则但 LLM 不调工具
 * 也可能是对的"这种灰区。旧实现只有"违规/不违规"两态，逼得维护者只能二选一：
 * 要么强行拦截（误伤正常回复），要么彻底不拦（守卫形同虚设——这正是本项目当前的状况：
 * 关键词→工具的映射完全不参与仲裁，只在 LLM 声称"已完成"时才起作用）。
 *
 * <p>三态把灰区显式化：{@link #AMBIGUOUS} 交给可选的 LLM 裁判或只记日志，
 * 不再被迫用一个二值判断去覆盖两种性质完全不同的情况。
 */
public enum AuditVerdict {

    /** 规则上看不出问题：没命中规则，或命中的规则其期望工具都已调用。 */
    PASS,

    /** 明确违规：命中规则、期望工具一个都没调，且 LLM 在文案里声称"已完成"。 */
    FAIL,

    /** 灰区：命中规则但工具没调（或只调了一部分），无法仅凭关键词断定对错。 */
    AMBIGUOUS
}
