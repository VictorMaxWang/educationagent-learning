package com.demo.agent.toolguard;

/**
 * 裁决结论的来源，用于埋点与排查"到底是规则判的还是裁判判的"。
 *
 * <p>把来源显式记录下来很重要：当裁决不符合预期时，第一件要问的就是
 * "这条结论是规则给的，还是 LLM 裁判给的，还是裁判失败后的规则兜底"。
 * 没有这个字段就只能靠翻日志猜。
 */
public enum JudgeSource {

    /** 纯规则裁决，未触发裁判。 */
    RULE,

    /** LLM 裁判给出了结论。 */
    LLM,

    /** 触发了裁判但裁判失败/超时/熔断，回退到规则结论。 */
    RULE_FALLBACK
}
